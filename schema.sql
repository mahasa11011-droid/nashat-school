-- =============================================================
-- منصة النشاط المدرسي — مخطط قاعدة البيانات وسياسات الصلاحيات
-- School activity portal — schema and Row Level Security policies.
--
-- شغّلي هذا الملف كاملًا في: Supabase Dashboard → SQL Editor → New query
-- Safe to run on an existing project: it creates nothing twice and
-- replaces the policies rather than duplicating them.
-- =============================================================

-- -------------------------------------------------------------
-- 1. الجداول / Tables
-- -------------------------------------------------------------
create table if not exists announcements (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  title       text not null,
  body        text
);

create table if not exists weekly_plan (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  term        text not null,
  week_number integer not null,
  date_range  text,
  title       text not null,
  details     text
);

create table if not exists events (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  title       text not null,
  event_date  date not null
);

create table if not exists photos (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  image_url   text not null,
  caption     text
);

create table if not exists wall_posts (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  author_name text not null,
  message     text not null,
  color       text not null default 'purple'
);

-- -------------------------------------------------------------
-- 2. حدود الطول على الحائط المفتوح للجميع
--    Length limits on the publicly-writable wall, enforced in the
--    database so they hold even if someone bypasses the form.
-- -------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'wall_posts_message_len') then
    alter table wall_posts add constraint wall_posts_message_len
      check (char_length(message) between 1 and 280) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'wall_posts_author_len') then
    alter table wall_posts add constraint wall_posts_author_len
      check (char_length(author_name) between 1 and 40) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'wall_posts_color_allowed') then
    alter table wall_posts add constraint wall_posts_color_allowed
      check (color in ('purple','maroon','orange','teal')) not valid;
  end if;
end $$;
-- NOT VALID means existing rows are left alone and only new posts are
-- checked. Once you have tidied any old over-long rows, you can run:
--   alter table wall_posts validate constraint wall_posts_message_len;

-- -------------------------------------------------------------
-- 3. سياسات الصلاحيات / Row Level Security
--
--    القراءة: مفتوحة للجميع (الموقع عام).
--    الكتابة: لرائدة النشاط المسجّلة الدخول فقط —
--             باستثناء الحائط، فهو مفتوح للنشر للجميع بالتصميم.
-- -------------------------------------------------------------
alter table announcements enable row level security;
alter table weekly_plan   enable row level security;
alter table events        enable row level security;
alter table photos        enable row level security;
alter table wall_posts    enable row level security;

-- الجداول التي تديرها رائدة النشاط وحدها
do $$
declare t text;
begin
  foreach t in array array['announcements','weekly_plan','events','photos'] loop
    execute format('drop policy if exists "public read" on %I', t);
    execute format('drop policy if exists "leader write" on %I', t);
    execute format('create policy "public read" on %I for select using (true)', t);
    execute format('create policy "leader write" on %I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- الحائط الإلكتروني: الجميع يقرأ وينشر، والحذف لرائدة النشاط فقط
drop policy if exists "public read"   on wall_posts;
drop policy if exists "public insert" on wall_posts;
drop policy if exists "leader delete" on wall_posts;
create policy "public read"   on wall_posts for select using (true);
create policy "public insert" on wall_posts for insert with check (true);
create policy "leader delete" on wall_posts for delete to authenticated using (true);

-- -------------------------------------------------------------
-- 4. مخزن الصور / Storage bucket
--    القراءة للجميع، والرفع والحذف لرائدة النشاط فقط.
-- -------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('nashat-photos', 'nashat-photos', true)
on conflict (id) do update set public = true;

drop policy if exists "photos public read"   on storage.objects;
drop policy if exists "photos leader write"  on storage.objects;
drop policy if exists "photos leader delete" on storage.objects;

create policy "photos public read" on storage.objects
  for select using (bucket_id = 'nashat-photos');

create policy "photos leader write" on storage.objects
  for insert to authenticated with check (bucket_id = 'nashat-photos');

create policy "photos leader delete" on storage.objects
  for delete to authenticated using (bucket_id = 'nashat-photos');

-- -------------------------------------------------------------
-- 5. التحقق / Verify
--    يجب أن تُظهر النتيجة rowsecurity = true لكل جدول.
-- -------------------------------------------------------------
select tablename, rowsecurity
from pg_tables
where schemaname = 'public'
  and tablename in ('announcements','weekly_plan','events','photos','wall_posts')
order by tablename;
